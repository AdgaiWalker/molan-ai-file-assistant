import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const contractsRoot = dirname(dirname(fileURLToPath(import.meta.url)));
export const nativeContractOutputPath = join(
  contractsRoot,
  '..',
  'native',
  'shared',
  'src',
  'commonMain',
  'kotlin',
  'com',
  'molan',
  'shared',
  'GeneratedContracts.kt',
);

const kotlinString = (value) => JSON.stringify(value);

export function renderNativeContracts() {
  const lifecycle = JSON.parse(readFileSync(join(contractsRoot, 'v1', 'lifecycle-rules.json'), 'utf8'));
  const formats = JSON.parse(readFileSync(join(contractsRoot, 'v1', 'format-handlers.json'), 'utf8'));

  const transitions = Object.entries(lifecycle.transitions).map(([state, targets]) => {
    const value = targets.length === 0
      ? 'emptySet()'
      : `setOf(${targets.map(kotlinString).join(', ')})`;
    return `    ${kotlinString(state)} to ${value},`;
  });

  const extensions = formats.handlers.flatMap((handler) =>
    handler.extensions.map((extension) =>
      `    ${kotlinString(extension)} to ${kotlinString(handler.formatId)},`));

  const signatureOwners = new Map();
  for (const handler of formats.handlers) {
    for (const hexPrefix of handler.detection.hexPrefixes ?? []) {
      const prefix = Buffer.from(hexPrefix, 'hex').toString('ascii');
      const owners = signatureOwners.get(prefix) ?? new Set();
      owners.add(handler.formatId);
      signatureOwners.set(prefix, owners);
    }
  }
  const signatures = [...signatureOwners.entries()]
    .filter(([, owners]) => owners.size === 1)
    .map(([prefix, owners]) =>
      `    ${kotlinString(prefix)} to ${kotlinString([...owners][0])},`);

  return `// Generated by contracts/src/generate-native-contracts.mjs. Do not edit.
// Sources: contracts/v1/lifecycle-rules.json and format-handlers.json
package com.molan.shared

internal val GeneratedLifecycleTransitions: Map<String, Set<String>> = mapOf(
${transitions.join('\n')}
)

internal val GeneratedExtensionFormats: Map<String, String> = mapOf(
${extensions.join('\n')}
)

internal val GeneratedSignatureFormats: List<Pair<String, String>> = listOf(
${signatures.join('\n')}
)

internal const val GeneratedFallbackFormat = ${kotlinString(formats.fallbackFormatId)}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(nativeContractOutputPath, renderNativeContracts());
  process.stdout.write(`已生成 ${nativeContractOutputPath}\n`);
}
